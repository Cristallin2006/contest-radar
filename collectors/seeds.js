    event_start: null,
    event_end: null,
    eligibility: null,
    team_size: null,
    fee: null,
    prize: null,
    url,
    source: "seed",
    source_url: url,
    description,
    tags: [yearTag, ...(rest.registration_deadline || rest.event_start ? [] : ["待官方公布"]), ...tags],
